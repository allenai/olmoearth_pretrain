"""Generate the ``*_year_aligned`` eval dataset configs.

The AEF supplemental evals and pastis_rslearn each feed OlmoEarth a temporal
window that does not match what the precomputed products (AEF, Tessera) are
built over. AEF and Tessera are calendar-year annual embeddings; our exports
are a trailing year from the observation date (canada, ethiopia, us_trees) or
a fixed Sep-Aug agricultural year (pastis). See
docs/PrecomputedEmbeddingCoverage.md and the eval-window discussion in
data/rslearn_dataset_configs/README.md.

This script writes, for each dataset, a sibling ``<name>_year_aligned`` config
directory holding a model.yaml whose imagery inputs are the twelve monthly
Sentinel-1 and Sentinel-2 layers used in pretraining
(``config_sentinel1.json`` / ``config_sentinel2_l2a.json``), in ascending
order. The matching rslearn ``config.json`` and the re-anchored windows are
produced on weka by ``reanchor_year_aligned_dataset.py``; the two must agree
on layer names, which is why both read MONTHLY_LAYERS from here.

Run from the repo root::

    python scripts/tools/build_year_aligned_eval_configs.py
    python scripts/tools/build_year_aligned_eval_configs.py --check
"""

import argparse
import copy
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
CONFIG_ROOT = REPO_ROOT / "data" / "rslearn_dataset_configs"
WEKA_ROOT = "/weka/dfive-default/olmoearth/eval_datasets"

SUFFIX = "_year_aligned"

# source config dir -> new eval task name
DATASETS = {
    "africa_crop_mask": "africa_crop_mask" + SUFFIX,
    "canada_crops_coarse": "canada_crops_coarse" + SUFFIX,
    "canada_crops_fine": "canada_crops_fine" + SUFFIX,
    "descals": "descals" + SUFFIX,
    "ethiopia_crops": "ethiopia_crops" + SUFFIX,
    "glance": "glance" + SUFFIX,
    "lcmap_lu": "lcmap_lu" + SUFFIX,
    "us_trees": "us_trees" + SUFFIX,
    # pastis_rslearn already uses the monthly layer scheme; only its anchor
    # moves (Sep 2018 -> Jan 2019), so the inputs block is unchanged.
    "pastis_rslearn": "pastis" + SUFFIX,
}

MONTHLY_LAYERS = {
    "sentinel2_l2a": [f"sentinel2_l2a_mo{i:02d}" for i in range(1, 13)],
    "sentinel1": [f"sentinel1_mo{i:02d}" for i in range(1, 13)],
}

# Band order must match the OlmoEarth modality band_order so the eval-time
# normalizer sees channels in the expected order (same rationale as the
# comment at the top of pastis_rslearn/model.yaml).
BANDS = {
    "sentinel2_l2a": [
        "B02",
        "B03",
        "B04",
        "B08",
        "B05",
        "B06",
        "B07",
        "B8A",
        "B11",
        "B12",
        "B01",
        "B09",
    ],
    "sentinel1": ["vv", "vh"],
}

HEADER = """\
# GENERATED by scripts/tools/build_year_aligned_eval_configs.py -- do not edit
# by hand; edit the generator and re-run.
#
# Year-aligned variant of {src}. Windows are anchored to the calendar year of
# the label (see reanchor_year_aligned_dataset.py), and imagery is the twelve
# ascending 30-day Sentinel-1 + Sentinel-2 layers used in pretraining. This
# makes the temporal support match what AEF and Tessera are built over, so
# OlmoEarth and the precomputed products are read over the same year.
#
# Kept deliberately separate from {src} rather than replacing it: the original
# numbers stay comparable to everything recorded against them.
"""


def imagery_input(modality: str) -> dict:
    """Build the model.yaml input block for one monthly imagery modality."""
    return {
        "data_type": "raster",
        "dtype": "FLOAT32",
        "layers": list(MONTHLY_LAYERS[modality]),
        "load_all_layers": True,
        "bands": list(BANDS[modality]),
        "passthrough": True,
    }


def convert(model_config: dict) -> dict:
    """Return a year-aligned copy of a model.yaml `data` block."""
    out = copy.deepcopy(model_config)
    init_args = out["data"]["init_args"]
    inputs = init_args["inputs"]

    # Replace whatever imagery the source used with the monthly layer scheme,
    # dropping any single-layer sentinel2 input, and insert both modalities in
    # a stable order ahead of the non-imagery inputs.
    for modality in ("sentinel2_l2a", "sentinel1", "sentinel2"):
        inputs.pop(modality, None)
    rebuilt = {
        "sentinel2_l2a": imagery_input("sentinel2_l2a"),
        "sentinel1": imagery_input("sentinel1"),
    }
    rebuilt.update(inputs)
    init_args["inputs"] = rebuilt

    # Any Pad transform must cover the newly added modality too, otherwise S1
    # keeps its native size and the shape check in the eval dataset trips.
    for transform in init_args.get("default_config", {}).get("transforms", []):
        selectors = transform.get("init_args", {}).get("image_selectors")
        if selectors and "sentinel2_l2a" in selectors and "sentinel1" not in selectors:
            selectors.insert(selectors.index("sentinel2_l2a") + 1, "sentinel1")

    return out


def main() -> int:
    """Write (or check) every year-aligned model.yaml."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if any generated file is missing or stale.",
    )
    args = parser.parse_args()

    stale: list[str] = []
    for src_name, dst_name in DATASETS.items():
        src_path = CONFIG_ROOT / src_name / "model.yaml"
        if not src_path.exists():
            raise FileNotFoundError(f"missing source config: {src_path}")

        config = convert(yaml.safe_load(src_path.read_text()))
        config["data"]["init_args"]["path"] = f"{WEKA_ROOT}/{dst_name}"

        rendered = HEADER.format(src=src_name) + yaml.safe_dump(
            config, sort_keys=False, default_flow_style=False, width=100
        )

        dst_path = CONFIG_ROOT / dst_name / "model.yaml"
        if args.check:
            if not dst_path.exists() or dst_path.read_text() != rendered:
                stale.append(dst_name)
            continue

        dst_path.parent.mkdir(parents=True, exist_ok=True)
        dst_path.write_text(rendered)
        print(f"wrote {dst_path.relative_to(REPO_ROOT)}")

    if stale:
        print(f"stale or missing: {', '.join(stale)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
