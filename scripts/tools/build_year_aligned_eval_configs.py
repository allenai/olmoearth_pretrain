"""Generate the ``*_year_aligned`` eval dataset configs.

The AEF supplemental evals and pastis_rslearn each feed OlmoEarth a temporal
window that does not match what the precomputed products (AEF, Tessera) are
built over. AEF and Tessera are calendar-year annual embeddings; our exports
are a trailing year from the observation date (canada, ethiopia, us_trees) or
a fixed Sep-Aug agricultural year (pastis). See
docs/PrecomputedEmbeddingCoverage.md and the eval-window discussion in
data/rslearn_dataset_configs/README.md.

This script writes, for each dataset, a sibling ``<name>_year_aligned`` config
directory holding a model.yaml whose imagery inputs are the twelve monthly
Sentinel-1 and Sentinel-2 layers used in pretraining
(``config_sentinel1.json`` / ``config_sentinel2_l2a.json``), in ascending
order. The matching rslearn ``config.json`` and the re-anchored windows are
produced on weka by ``reanchor_year_aligned_dataset.py``; the two must agree
on layer names, which is why both read MONTHLY_LAYERS from here.

Run from the repo root::

    python scripts/tools/build_year_aligned_eval_configs.py
    python scripts/tools/build_year_aligned_eval_configs.py --check

``--check`` compares bytes, so a file that ``wire_embedding_modalities.py``
has since edited reads as stale even when nothing semantic differs: that
script inserts its input block directly under ``inputs:`` with its own list
indentation, while this one re-dumps the whole mapping. Regenerating is safe
(PRESERVED_INPUTS keeps those blocks and their ``required`` flags), but it
reformats, which unlinks ``config_repo_dir`` until the Weka copy is re-synced
-- so check what actually differs before regenerating a wired dataset.
"""

import argparse
import copy
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
CONFIG_ROOT = REPO_ROOT / "data" / "rslearn_dataset_configs"
WEKA_ROOT = "/weka/dfive-default/olmoearth/eval_datasets"

SUFFIX = "_year_aligned"

# source config dir -> new eval task name
DATASETS = {
    "africa_crop_mask": "africa_crop_mask" + SUFFIX,
    "canada_crops_coarse": "canada_crops_coarse" + SUFFIX,
    "canada_crops_fine": "canada_crops_fine" + SUFFIX,
    "descals": "descals" + SUFFIX,
    "ethiopia_crops": "ethiopia_crops" + SUFFIX,
    "glance": "glance" + SUFFIX,
    "lcmap_lu": "lcmap_lu" + SUFFIX,
    "us_trees": "us_trees" + SUFFIX,
    # pastis_rslearn already uses the monthly layer scheme; only its anchor
    # moves (Sep 2018 -> Jan 2019), so the inputs block is unchanged.
    "pastis_rslearn": "pastis" + SUFFIX,
}

# Precomputed-embedding inputs that wire_embedding_modalities.py adds to a
# dataset's model.yaml once its bake is complete (its PRODUCT_TO_MODALITY, plus
# gse for aef). Those edits land on the year-aligned file only -- a product can
# be wired on the year-aligned dataset and not on its parent, as tessera is on
# us_trees_year_aligned and tessera_v2 is on the two v2 exports -- so
# regenerating from the parent would silently delete them and drop the
# baseline. Anything here that the destination already declares is carried
# through unchanged.
PRESERVED_INPUTS = ("gse", "tessera", "tessera_v11", "tessera_v2")

MONTHLY_LAYERS = {
    "sentinel2_l2a": [f"sentinel2_l2a_mo{i:02d}" for i in range(1, 13)],
    "sentinel1": [f"sentinel1_mo{i:02d}" for i in range(1, 13)],
}

# S2 scene-classification layers, added on weka by setup_extra_layers.py.
# The loader turns them into per-pixel cloud masks (scl_cloud_mask=True); they
# are never fed to the model as a modality. required stays False: a required
# input shrinks the evaluated window set for EVERY model on the dataset, which
# would detach it from the published year-aligned numbers.
SCL_LAYERS = [f"sentinel2_scl_mo{i:02d}" for i in range(1, 13)]

# Landsat monthlies, also added on weka by setup_extra_layers.py (input parity
# with AEF, which ingests Landsat). A real modality, unlike scl -- but
# required stays False for the same window-set reason, which means windows
# with Landsat coverage gaps lack the input entirely: measure per-dataset
# completeness before registering any landsat eval task.
LANDSAT_LAYERS = [f"landsat_mo{i:02d}" for i in range(1, 13)]

# Band order must match Modality.LANDSAT.band_order (B8 first: its band sets
# list the 15 m pan band before the 30 m bands), same rationale as BANDS.
LANDSAT_BANDS = ["B8", "B1", "B2", "B3", "B4", "B5", "B6", "B7", "B9", "B10", "B11"]

# Band order must match the OlmoEarth modality band_order so the eval-time
# normalizer sees channels in the expected order (same rationale as the
# comment at the top of pastis_rslearn/model.yaml).
BANDS = {
    "sentinel2_l2a": [
        "B02",
        "B03",
        "B04",
        "B08",
        "B05",
        "B06",
        "B07",
        "B8A",
        "B11",
        "B12",
        "B01",
        "B09",
    ],
    "sentinel1": ["vv", "vh"],
}

HEADER = """\
# GENERATED by scripts/tools/build_year_aligned_eval_configs.py -- do not edit
# by hand; edit the generator and re-run.
#
# Year-aligned variant of {src}. Windows are anchored to the calendar year of
# the label (see reanchor_year_aligned_dataset.py), and imagery is the twelve
# ascending 30-day Sentinel-1 + Sentinel-2 layers used in pretraining. This
# makes the temporal support match what AEF and Tessera are built over, so
# OlmoEarth and the precomputed products are read over the same year.
#
# Kept deliberately separate from {src} rather than replacing it: the original
# numbers stay comparable to everything recorded against them.
"""


def imagery_input(modality: str) -> dict:
    """Build the model.yaml input block for one monthly imagery modality."""
    return {
        "data_type": "raster",
        "dtype": "FLOAT32",
        "layers": list(MONTHLY_LAYERS[modality]),
        "load_all_layers": True,
        "bands": list(BANDS[modality]),
        "passthrough": True,
    }


def scl_input() -> dict:
    """Build the optional model.yaml input block for the SCL cloud-mask layers."""
    return {
        "data_type": "raster",
        "dtype": "FLOAT32",
        "layers": list(SCL_LAYERS),
        "load_all_layers": True,
        "bands": ["SCL"],
        "passthrough": True,
        "required": False,
    }


def landsat_input() -> dict:
    """Build the optional model.yaml input block for the Landsat monthlies."""
    return {
        "data_type": "raster",
        "dtype": "FLOAT32",
        "layers": list(LANDSAT_LAYERS),
        "load_all_layers": True,
        "bands": list(LANDSAT_BANDS),
        "passthrough": True,
        "required": False,
    }


def preserved_inputs(dst_path: Path, source_inputs: dict) -> tuple[dict, dict]:
    """Embedding inputs to take from the destination rather than the parent.

    wire_embedding_modalities.py owns these blocks: it adds them when a bake
    completes and flips ``required`` when the product goes live, on the
    year-aligned file independently of the parent. Regenerating from the
    parent would undo both.

    Args:
        dst_path: the generated model.yaml, which may not exist yet.
        source_inputs: the parent dataset's inputs.

    Returns:
        (new, overrides) — inputs the destination has and the source does not,
        and destination versions of inputs the source also declares.
    """
    if not dst_path.exists():
        return {}, {}
    existing = yaml.safe_load(dst_path.read_text())["data"]["init_args"]["inputs"]
    embedding = {n: b for n, b in existing.items() if n in PRESERVED_INPUTS}
    return (
        {n: b for n, b in embedding.items() if n not in source_inputs},
        {n: b for n, b in embedding.items() if n in source_inputs},
    )


def convert(
    model_config: dict,
    carry_over: dict | None = None,
    overrides: dict | None = None,
) -> dict:
    """Return a year-aligned copy of a model.yaml `data` block.

    Args:
        model_config: the parsed parent model.yaml.
        carry_over: destination-only inputs to keep, inserted ahead of the
            target input (see preserved_inputs).
        overrides: destination versions of inputs the parent also declares,
            kept in the parent's position.

    Returns:
        the converted config.
    """
    out = copy.deepcopy(model_config)
    init_args = out["data"]["init_args"]
    inputs = init_args["inputs"]

    # Replace whatever imagery the source used with the monthly layer scheme,
    # dropping any single-layer sentinel2 input, and insert both modalities in
    # a stable order ahead of the non-imagery inputs. scl rides along as the
    # optional cloud-mask input (see scl_input), landsat as the optional
    # third sensor (see landsat_input).
    for modality in ("sentinel2_l2a", "sentinel1", "sentinel2", "scl", "landsat"):
        inputs.pop(modality, None)
    rebuilt = {
        "sentinel2_l2a": imagery_input("sentinel2_l2a"),
        "sentinel1": imagery_input("sentinel1"),
        "scl": scl_input(),
        "landsat": landsat_input(),
    }
    for name, block in inputs.items():
        # Keep "targets" last so a carried-over input reads next to the other
        # embedding inputs rather than after the label.
        if name == "targets" and carry_over:
            rebuilt.update(carry_over)
            carry_over = None
        rebuilt[name] = (overrides or {}).get(name, block)
    if carry_over:
        rebuilt.update(carry_over)
    init_args["inputs"] = rebuilt

    # Any Pad transform must cover the newly added modalities too, otherwise
    # S1/SCL/Landsat keep their native size and the shape check in the eval
    # dataset trips (for SCL, the mask would be misaligned with the padded
    # imagery).
    for transform in init_args.get("default_config", {}).get("transforms", []):
        selectors = transform.get("init_args", {}).get("image_selectors")
        if selectors and "sentinel2_l2a" in selectors:
            for extra in ("sentinel1", "scl", "landsat"):
                if extra not in selectors:
                    selectors.insert(selectors.index("sentinel2_l2a") + 1, extra)

    return out


def main() -> int:
    """Write (or check) every year-aligned model.yaml."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if any generated file is missing or stale.",
    )
    args = parser.parse_args()

    stale: list[str] = []
    for src_name, dst_name in DATASETS.items():
        src_path = CONFIG_ROOT / src_name / "model.yaml"
        if not src_path.exists():
            raise FileNotFoundError(f"missing source config: {src_path}")

        source = yaml.safe_load(src_path.read_text())
        dst_path = CONFIG_ROOT / dst_name / "model.yaml"
        carry_over, overrides = preserved_inputs(
            dst_path, source["data"]["init_args"]["inputs"]
        )
        config = convert(source, carry_over=carry_over, overrides=overrides)
        config["data"]["init_args"]["path"] = f"{WEKA_ROOT}/{dst_name}"

        rendered = HEADER.format(src=src_name) + yaml.safe_dump(
            config, sort_keys=False, default_flow_style=False, width=100
        )

        if args.check:
            if not dst_path.exists() or dst_path.read_text() != rendered:
                stale.append(dst_name)
            continue

        dst_path.parent.mkdir(parents=True, exist_ok=True)
        dst_path.write_text(rendered)
        print(f"wrote {dst_path.relative_to(REPO_ROOT)}")

    if stale:
        print(f"stale or missing: {', '.join(stale)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
